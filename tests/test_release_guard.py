def _metadata(name, version):
    return (f'Metadata-Version: 2.1\nName: {name}\nVersion: {version}\n'
            'Summary: synthetic test artifact\n').encode()


def build_verified(root, *, dist_ver='0.1.0', tag='v0.1.0',
                   wheel_meta_ver=None, sdist_meta_ver=None,
                   wheel_meta_name='quoth', sdist_meta_name='quoth',
                   extra_dist=(), sums='compute', source_sha=SHA,
                   source_file=None, reqs_ver=None, reqs_text=None):
    """Materialize a synthetic verified/ artifact layout under root."""
    verified = root / 'verified'
    dist = verified / 'dist'
    (verified / 'artifacts').mkdir(parents=True)
    dist.mkdir(exist_ok=True)
    wheel_name = f'quoth-{dist_ver}-py3-none-any.whl'
    sdist_name = f'quoth-{dist_ver}.tar.gz'
    wheel = dist / wheel_name
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, 'w') as zf:
        zf.writestr(f'quoth-{dist_ver}.dist-info/METADATA',
                    _metadata(wheel_meta_name, wheel_meta_ver or dist_ver))
        zf.writestr('quoth/__init__.py', b"__version__ = 'synthetic'\n")
    wheel.write_bytes(buf.getvalue())
    sdist = dist / sdist_name
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode='w:gz') as tf:
        pkg = f'quoth-{dist_ver}'
        info = tarfile.TarInfo(f'{pkg}/PKG-INFO')
        data = _metadata(sdist_meta_name, sdist_meta_ver or dist_ver)
        info.size = len(data)
        tf.addfile(info, io.BytesIO(data))
        src = tarfile.TarInfo(f'{pkg}/src/quoth/__init__.py')
        payload = b"__version__ = 'synthetic'\n"
        src.size = len(payload)
        tf.addfile(src, io.BytesIO(payload))
    sdist.write_bytes(buf.getvalue())
    reqs = dist / f'quoth-{reqs_ver or dist_ver}-requirements.txt'
    reqs.write_text(REQS if reqs_text is None else reqs_text)
    for name, blob in extra_dist:
        (dist / name).write_bytes(blob)
    (verified / 'artifacts' / 'source-commit.txt').write_text(
        (source_sha if source_file is None else source_file) + '\n')
    if sums != 'omit':
        reqs_sum = (f'dist/{reqs.name}', rg._sha256(reqs))
        entries = {'compute': [(f'dist/{wheel.name}', rg._sha256(wheel)),
                               (f'dist/{sdist.name}', rg._sha256(sdist)), reqs_sum],
                   'only-wheel': [(f'dist/{wheel.name}', rg._sha256(wheel))],
                   'no-reqs': [(f'dist/{wheel.name}', rg._sha256(wheel)),
                               (f'dist/{sdist.name}', rg._sha256(sdist))],
                   'corrupt': [(f'dist/{wheel.name}', '0' * 64),
                               (f'dist/{sdist.name}', rg._sha256(sdist)), reqs_sum],
                   'extra': [(f'dist/{wheel.name}', rg._sha256(wheel)),
                             (f'dist/{sdist.name}', rg._sha256(sdist)), reqs_sum,
                             ('dist/evil.bin', 'c' * 64)]}[sums]
        (verified / 'artifacts' / 'SHA256SUMS').write_text(
            ''.join(f'{d}  {p}\n' for p, d in entries))
    return verified


class FakeGh:
    """Deterministic stand-in for the gh CLI transport."""

    def __init__(self, *, private=True, tag_commit=SHA, pre_view=('missing', None),
                 post_view='reflect', create_rc=0, create_stderr='',
                 download='real', download_rc=0):
        self.private = private
        self._tag_commit = tag_commit
        self.pre_view = pre_view
        self.post_view: object = post_view
        self.create_rc = create_rc
        self.create_stderr = create_stderr
        self.download = download
        self.download_rc = download_rc
        self.created = False
        self.create_calls = []
        self.download_calls = 0

    def repo_is_private(self):
        return self.private

    def tag_commit(self, tag):
        return self._tag_commit

    def release_view(self, tag):
        if not self.created:
            return self.pre_view
        if self.post_view == 'reflect':
            return 'exists', self._reflected
        return self.post_view

    def release_create(self, tag, files, title, notes):
        self.created = True
        self.create_calls.append([tag, list(files), title, notes])
        return subprocess.CompletedProcess(['gh', 'release', 'create'], self.create_rc,
                                           stderr=self.create_stderr)

    def release_download(self, tag, dest):
        self.download_calls += 1
        if self.download_rc != 0:
            return subprocess.CompletedProcess(['gh', 'release', 'download'],
                                               self.download_rc, stderr='download failed')
        plan = self._plan
        for name in plan['expected_assets']:
            local = Path(plan['paths'][name])
            blob = local.read_bytes()
            if self.download == 'corrupt':
                blob = blob + b'corrupted'
            (Path(dest) / name).write_bytes(blob)
        if self.download == 'extra':
            (Path(dest) / 'attacker-extra.bin').write_bytes(b'extra')
        return subprocess.CompletedProcess(['gh', 'release', 'download'], 0)

    def bind(self, plan):
        self._plan = plan
        assets = []
        for name in plan['expected_assets']:
            assets.append({'name': name, 'size': plan['sizes'][name],
                           'digest': f"sha256:{plan['sha256'][name]}"})
        self._reflected = {'tagName': plan['tag'], 'assets': assets}
        return self


def expect_plan_failure(root, tag, source_sha, fragment):
    with pytest.raises(rg.GuardError) as exc:
        rg.plan_release(root / 'verified', tag, source_sha)
    assert fragment in str(exc.value)


