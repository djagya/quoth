def planned(tmp_path, **kwargs):
    build_verified(tmp_path, **kwargs)
    return rg.plan_release(tmp_path / 'verified',
                           kwargs.get('tag', 'v0.1.0'), SHA)


def exact_readback_assets(plan):
    """An honest post-create asset inventory for the plan."""
    return [{'name': n, 'size': plan['sizes'][n],
             'digest': f"sha256:{plan['sha256'][n]}"} for n in plan['expected_assets']]


def test_successful_delivery_exact_identity_readback(tmp_path, capsys):
    plan = planned(tmp_path)
    gh = FakeGh().bind(plan)
    receipt = rg.deliver(plan, gh)
    assert len(gh.create_calls) == 1
    tag, files, title, notes = gh.create_calls[0]
    assert tag == 'v0.1.0'
    assert '--verify-tag' not in files  # flag handled by real transport
    assert [Path(f).name for f in files] == ['quoth-0.1.0-py3-none-any.whl',
                                             'quoth-0.1.0.tar.gz',
                                             'quoth-0.1.0-requirements.txt']
    assert receipt['published'] == 'v0.1.0'
    assert receipt['readback'] == 'exact names, sizes, digests and downloaded bytes'
    assert receipt['assets'] == plan['sha256']
    out = capsys.readouterr().out
    assert '"published": "v0.1.0"' in out


def test_real_transport_never_creates_tags(monkeypatch):
    """The concrete gh transport builds the create argv with --verify-tag."""
    argvs = []
    monkeypatch.setattr(rg.subprocess, 'run',
                        lambda argv, **kw: argvs.append(list(argv))
                        or subprocess.CompletedProcess(argv, 0, stdout='{}'))
    gh = rg.Gh('synthetic/quoth')
    gh.release_create('v0.1.0', ['w.whl', 's.tar.gz'], 't', 'n')
    create = next(a for a in argvs if a[:3] == ['gh', 'release', 'create'])
    assert '--verify-tag' in create
    assert create[1] == 'release' and create[2] == 'create'
    # tag creation / deletion verbs are never invoked anywhere in the transport
    for forbidden in (['gh', 'tag', 'create'], ['gh', 'tag', 'delete'],
                      ['git', 'push'], ['git', 'tag']):
        assert forbidden not in [a[:3] for a in argvs]


